-- Исправляет политику INSERT для таблицы profiles:
-- разрешает пользователю создавать только свою строку профиля.
-- Применяется для баз, где уже запущена миграция 007.
-- ─────────────────────────────────────────────────────────────────────────────

-- Удаляем старую запрещающую политику
DROP POLICY IF EXISTS "profiles: no direct insert" ON public.profiles;

-- Добавляем корректную: пользователь может вставить только свою строку
CREATE POLICY "profiles: insert own"
  ON public.profiles
  FOR INSERT
  WITH CHECK (auth.uid() = id);
